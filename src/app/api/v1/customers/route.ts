import { HTTP_STATUS } from "@/constants/http-status.constant";
import { errorResponse, successResponse } from "@/lib/api/api-response";
import {
	authenticationMiddleware,
	authorizationMiddleware,
} from "@/lib/api/auth.middleware";
import { getHttpErrorStatus } from "@/lib/api/get-http-error-status";
import { getSafeErrorMessage } from "@/lib/api/get-safe-error-message";
import { HttpError } from "@/lib/api/http-error";
import { normalizeError } from "@/lib/errors/normalize-error";
import { customerService, createCustomerSchema } from "@/services/customer.service";
import { NextResponse } from "next/server";

export async function GET(request: Request) {
	try {
		const session = await authenticationMiddleware();
		await authorizationMiddleware({
			allowedRole: ["admin", "sales", "dealer"],
			currentRole: session.user.role,
		});

		const url = new URL(request.url);
		const typeParam = url.searchParams.get("type");
		const dealerIdParam = url.searchParams.get("dealerId");

		let data;
		if (session.user.role === "dealer") {
			data = await customerService.getAll({
				dealerId: session.user.id,
				type: "DEALER",
			});
		} else {
			data = await customerService.getAll({
				dealerId: dealerIdParam ?? undefined,
				type: typeParam === "DEALER" || typeParam === "MKO" ? typeParam : "MKO",
			});
		}

		return NextResponse.json(
			successResponse({
				message: "Success",
				data,
			}),
			{ status: HTTP_STATUS.OK.code },
		);
	} catch (error) {
		if (error instanceof HttpError) {
			return NextResponse.json(
				errorResponse({
					message: error.message,
					issues: [],
				}),
				{ status: error.statusCode },
			);
		}

		const normalized = normalizeError(error);
		return NextResponse.json(
			errorResponse({
				message: getSafeErrorMessage(normalized),
				issues: normalized.issues,
			}),
			{ status: getHttpErrorStatus(normalized) },
		);
	}
}

export async function POST(request: Request) {
	try {
		const session = await authenticationMiddleware();
		await authorizationMiddleware({
			allowedRole: ["admin", "sales", "dealer"],
			currentRole: session.user.role,
		});

		const body = await request.json();
		let parsedBody = createCustomerSchema.parse(body);

		// Dealers can only create their own DEALER-type customers; customId is auto-generated by the service.
		if (session.user.role === "dealer") {
			parsedBody = {
				...parsedBody,
				type: "DEALER",
				dealerId: session.user.id,
				customId: undefined,
			};
		}

		const ipAddress =
			request.headers.get("x-forwarded-for")?.split(",")[0].trim() ??
			request.headers.get("x-real-ip");
		const userAgent = request.headers.get("user-agent");

		const data = await customerService.create(parsedBody, {
			userId: session.user.id,
			role: session.user.role,
			ipAddress,
			userAgent,
		});

		return NextResponse.json(
			successResponse({ message: "Customer berhasil ditambahkan", data }),
			{ status: HTTP_STATUS.CREATED.code },
		);
	} catch (error) {
		if (error instanceof HttpError) {
			return NextResponse.json(
				errorResponse({ message: error.message, issues: [] }),
				{ status: error.statusCode },
			);
		}

		const normalized = normalizeError(error);
		return NextResponse.json(
			errorResponse({
				message: getSafeErrorMessage(normalized),
				issues: normalized.issues,
			}),
			{ status: getHttpErrorStatus(normalized) },
		);
	}
}
